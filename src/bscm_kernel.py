# Named Bell-prior weight presets.  Order: (w_{Phi+}, w_{Phi-}, w_{Psi+}, w_{Psi-}).
BELL_WEIGHT_PRESETS = {
    # Canonical BSCM: uniform prior over the 4 Bell sectors.  Yields
    # H = (1/2) I + (1/2) cos x_i cos x_j  XX + (1/2) sin x_i sin x_j  YY,
    # ZZ coefficient identically zero (single-pair P2).
    "uniform": (1.0, 1.0, 1.0, 1.0),
    # Even-parity (Phi) sector only: emphasises the |Phi+>, |Phi-> subspace.
    # H_pair has feature-dependent coefficient on (XX - YY) (pair creation),
    # constant ZZ (no feature-dependent ZZ entanglement).
    "phi_only": (2.0, 2.0, 0.0, 0.0),
    # Odd-parity (Psi) sector only: emphasises the |Psi+>, |Psi-> subspace.
    # H_pair has equal feature-dependent coefficients on (XX + YY) (hopping),
    # constant ZZ.
    "psi_only": (0.0, 0.0, 2.0, 2.0),
}


def bscm_pauli_coefficients(
    x_i: float, x_j: float,
    weights: Tuple[float, float, float, float] = BELL_WEIGHT_PRESETS["uniform"],
) -> Tuple[float, float, float]:
    """Per-pair Pauli coefficients (alpha_XX, alpha_YY, alpha_ZZ) in the
    Hamiltonian generated by Bell-projector weights `weights`.

    H_{ij}(x_i, x_j; w) = sum_k w_k * (Bell amplitude)_k * |Bell_k><Bell_k|
                        = (alpha_II) I + alpha_XX XX + alpha_YY YY + alpha_ZZ ZZ.

    The Bell-amplitude weights are
        c_plus  = cos^2((x_i + x_j)/2)
        s_plus  = sin^2((x_i + x_j)/2)
        c_minus = cos^2((x_i - x_j)/2)
        s_minus = sin^2((x_i - x_j)/2)
    and the closed-form Pauli coefficients (from the |Bell><Bell| =
    Pauli expansion) are returned.

    For weights = (1, 1, 1, 1) (uniform):
        alpha_XX = (1/2) cos x_i cos x_j
        alpha_YY = (1/2) sin x_i sin x_j
        alpha_ZZ = 0  (P2)
    """
    w1, w2, w3, w4 = weights
    cp = np.cos((x_i + x_j) / 2.0) ** 2
    sp = np.sin((x_i + x_j) / 2.0) ** 2
    cm = np.cos((x_i - x_j) / 2.0) ** 2
    sm = np.sin((x_i - x_j) / 2.0) ** 2
    a_xx = (w1 * cp - w2 * sp + w3 * cm - w4 * sm) / 4.0
    a_yy = (-w1 * cp + w2 * sp + w3 * cm - w4 * sm) / 4.0
    a_zz = (w1 * cp + w2 * sp - w3 * cm - w4 * sm) / 4.0
    return float(a_xx), float(a_yy), float(a_zz)


def bscm_xy_coefficients(x_i: float, x_j: float) -> Tuple[float, float]:
    """Backward-compatible accessor: returns (alpha_XX, alpha_YY) for the
    canonical uniform-prior BSCM.  Equivalent to
    bscm_pauli_coefficients(x_i, x_j)[:2] when weights == 'uniform'.
    """
    a_xx, a_yy, _ = bscm_pauli_coefficients(x_i, x_j)
    return a_xx, a_yy


def coupling_strength(
    x_i: float, x_j: float,
    weights: Tuple[float, float, float, float] = BELL_WEIGHT_PRESETS["uniform"],
) -> float:
    """Scalar coupling strength for sparsification: max(|a_XX|, |a_YY|, |a_ZZ|)."""
    a, b, c = bscm_pauli_coefficients(x_i, x_j, weights)
    return max(abs(a), abs(b), abs(c))


# ============================================================================
# BSCM Feature Map Circuit
# ============================================================================

def _resolve_pairs(n_qubits: int, connectivity: str) -> List[Tuple[int, int]]:
    if connectivity == "all":
        return [(i, j) for i in range(n_qubits) for j in range(i + 1, n_qubits)]
    if connectivity == "linear":
        return [(i, i + 1) for i in range(n_qubits - 1)]
    if connectivity == "cross":
        mid = n_qubits // 2
        return [(i, j) for i in range(mid) for j in range(mid, n_qubits)]
    raise ValueError(f"Unknown connectivity: {connectivity}")


def apply_bscm_feature_map(
    x: np.ndarray,
    n_qubits: int = config.N_QUBITS,
    reps: int = config.ZZ_REPS,
    tau: float = 1.0,
    coupling_threshold: float = 1e-4,
    connectivity: str = "all",
    bell_weights: Tuple[float, float, float, float]
        = BELL_WEIGHT_PRESETS["uniform"],
    singlet_gated: bool = False,
) -> None:
    """Apply U(x) = product of BSCM layers, in-place inside a QNode.

    Per layer:
        1. H on every qubit.
        2. RZ(x_i) on every qubit (single-qubit feature encoding).
        3. For each pair (i, j) in the connectivity, apply
             IsingXX( 2 * tau * a_xx )
             IsingYY( 2 * tau * a_yy )
             IsingZZ( 2 * tau * a_zz )
           where (a_xx, a_yy, a_zz) = bscm_pauli_coefficients(x_i, x_j; w).
           XX, YY, ZZ all commute pairwise on the same two qubits, so the
           gate order within a pair is irrelevant.

    For the canonical 'uniform' Bell-prior, a_zz is identically zero and
    only IsingXX, IsingYY are emitted.  Non-uniform priors generate a
    feature-dependent ZZ component, providing ablation control.

    Singlet gating (singlet_gated=True):
        Multiplies each pair's Pauli coefficients by the singlet fraction
        w_{Psi-} = sin^2((x_i - x_j) / 2).  This suppresses entanglement
        between qubits encoding similar feature values (x_i ~ x_j),
        preventing kernel concentration on correlated feature sets while
        preserving the BSCM XX+YY Pauli structure.
    """
    import pennylane as qml

    pairs = _resolve_pairs(n_qubits, connectivity)

    for _ in range(reps):
        for i in range(n_qubits):
            qml.Hadamard(wires=i)
        for i in range(n_qubits):
            qml.RZ(x[i], wires=i)
        for qi, qj in pairs:
            a_xx, a_yy, a_zz = bscm_pauli_coefficients(
                x[qi], x[qj], bell_weights
            )
            # Singlet-gated BSCM: modulate by the singlet fraction.
            if singlet_gated:
                sg = float(np.sin((x[qi] - x[qj]) / 2.0) ** 2)
                a_xx *= sg
                a_yy *= sg
                a_zz *= sg
            if max(abs(a_xx), abs(a_yy), abs(a_zz)) < coupling_threshold:
                continue
            if abs(a_xx) >= coupling_threshold:
                qml.IsingXX(2.0 * tau * a_xx, wires=[qi, qj])
            if abs(a_yy) >= coupling_threshold:
                qml.IsingYY(2.0 * tau * a_yy, wires=[qi, qj])
            if abs(a_zz) >= coupling_threshold:
                qml.IsingZZ(2.0 * tau * a_zz, wires=[qi, qj])


def apply_bscm_feature_map_adjoint(
    x: np.ndarray,
    n_qubits: int = config.N_QUBITS,
    reps: int = config.ZZ_REPS,
    tau: float = 1.0,
    coupling_threshold: float = 1e-4,
    connectivity: str = "all",
    bell_weights: Tuple[float, float, float, float]
        = BELL_WEIGHT_PRESETS["uniform"],
    singlet_gated: bool = False,
) -> None:
    """Apply U^dagger(x) by reversing the gate ordering and negating angles."""
    import pennylane as qml

    pairs = _resolve_pairs(n_qubits, connectivity)

    for _ in range(reps):
        for qi, qj in reversed(pairs):
            a_xx, a_yy, a_zz = bscm_pauli_coefficients(
                x[qi], x[qj], bell_weights
            )
            if singlet_gated:
                sg = float(np.sin((x[qi] - x[qj]) / 2.0) ** 2)
                a_xx *= sg
                a_yy *= sg
                a_zz *= sg
            if max(abs(a_xx), abs(a_yy), abs(a_zz)) < coupling_threshold:
                continue
            if abs(a_zz) >= coupling_threshold:
                qml.IsingZZ(-2.0 * tau * a_zz, wires=[qi, qj])
            if abs(a_yy) >= coupling_threshold:
                qml.IsingYY(-2.0 * tau * a_yy, wires=[qi, qj])
            if abs(a_xx) >= coupling_threshold:
                qml.IsingXX(-2.0 * tau * a_xx, wires=[qi, qj])
        for i in range(n_qubits - 1, -1, -1):
            qml.RZ(-x[i], wires=i)
        for i in range(n_qubits - 1, -1, -1):
            qml.Hadamard(wires=i)


