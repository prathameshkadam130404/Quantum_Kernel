# Projected Quantum Kernel (PQK) — Bloch-Vector Extraction
# ============================================================================

def extract_bscm_bloch_vectors(
    X: np.ndarray,
    n_qubits: int = config.N_QUBITS,
    reps: int = config.ZZ_REPS,
    tau: float = 1.0,
    coupling_threshold: float = 1e-4,
    connectivity: str = "all",
    bell_weights: Tuple[float, float, float, float]
        = BELL_WEIGHT_PRESETS["uniform"],
    singlet_gated: bool = False,
    cache_path: Optional[str] = None,
    desc: str = "BSCM-PQK",
) -> np.ndarray:
    """Extract per-qubit Bloch vectors from the BSCM feature-map circuit.

    For each sample x, runs U(x)|0...0⟩ (the *forward* feature map only —
    no adjoint) and measures the three single-qubit Pauli expectations
    ⟨X_q⟩, ⟨Y_q⟩, ⟨Z_q⟩ on each qubit q.

    This is the "Projected Quantum Kernel" (PQK) approach of Huang et al.
    (Nature Comm. 2021): instead of computing the fidelity |⟨ψ(x')|ψ(x)⟩|²
    (which requires N² circuit pairs), we extract a 3·n_q–dimensional
    classical feature vector per sample (N circuit executions total), then
    build a classical RBF kernel on these vectors.

    The BSCM variant uses the XX+YY entangling layer (with optional
    singlet gating) rather than SRQFM's ZZ layer, so the Bloch vectors
    encode different inter-qubit correlations — specifically, the X and Y
    components carry information from the non-commuting IsingXX/IsingYY
    channels that fidelity-based BSCM would squash via concentration.

    Args:
        X:            (N, n_qubits) encoded feature matrix in [0, π].
        n_qubits:     Number of qubits (= feature dimension).
        reps:         Circuit repetitions.
        tau:          Time-evolution scaling.
        coupling_threshold: Minimum |coefficient| to emit a gate.
        connectivity: Qubit pair topology ("all", "linear", "cross").
        bell_weights: Bell-sector prior weights.
        singlet_gated: If True, multiply Pauli coefficients by the singlet
                       fraction sin²((x_i − x_j)/2) before gating.
        cache_path:   If set, save/load Bloch array to/from this .npy path.
        desc:         Progress bar label.

    Returns:
        (N, 3 * n_qubits) float64 array.  Layout per sample:
        [⟨X_0⟩, ⟨Y_0⟩, ⟨Z_0⟩, ⟨X_1⟩, ⟨Y_1⟩, ⟨Z_1⟩, ...].
    """
    import pennylane as qml

    # Cache check.
    if cache_path is not None and os.path.exists(cache_path):
        bloch = np.load(cache_path)
        expected_shape = (len(X), 3 * n_qubits)
        if bloch.shape == expected_shape:
            logger.info("[CACHE] Loaded Bloch vectors from %s", cache_path)
            return bloch
        logger.warning(
            "[CACHE] Shape mismatch %s vs %s — recomputing.",
            bloch.shape, expected_shape,
        )

    dev = config.get_device(n_qubits)

    # Build three QNodes: one per Pauli basis.
    # Each runs U(x)|0⟩ then measures ⟨σ_q⟩ on all qubits simultaneously.

    @qml.qnode(dev, diff_method=None)
    def _measure_pauli_x(x):
        apply_bscm_feature_map(
            x, n_qubits, reps, tau, coupling_threshold, connectivity,
            bell_weights, singlet_gated,
        )
        return [qml.expval(qml.PauliX(q)) for q in range(n_qubits)]

    @qml.qnode(dev, diff_method=None)
    def _measure_pauli_y(x):
        apply_bscm_feature_map(
            x, n_qubits, reps, tau, coupling_threshold, connectivity,
            bell_weights, singlet_gated,
        )
        return [qml.expval(qml.PauliY(q)) for q in range(n_qubits)]

    @qml.qnode(dev, diff_method=None)
    def _measure_pauli_z(x):
        apply_bscm_feature_map(
            x, n_qubits, reps, tau, coupling_threshold, connectivity,
            bell_weights, singlet_gated,
        )
        return [qml.expval(qml.PauliZ(q)) for q in range(n_qubits)]

    N = len(X)
    bloch = np.zeros((N, 3 * n_qubits), dtype=np.float64)

    t0 = time.time()
    for idx in tqdm(range(N), desc=f"{desc} Bloch (N={N})", unit="sample"):
        bx = np.asarray(_measure_pauli_x(X[idx]), dtype=np.float64)
        by = np.asarray(_measure_pauli_y(X[idx]), dtype=np.float64)
        bz = np.asarray(_measure_pauli_z(X[idx]), dtype=np.float64)
        for q in range(n_qubits):
            bloch[idx, 3 * q]     = bx[q]
            bloch[idx, 3 * q + 1] = by[q]
            bloch[idx, 3 * q + 2] = bz[q]

    elapsed = time.time() - t0
    logger.info(
        "%s Bloch extraction: %d samples in %.0f s (%.1f min)",
        desc, N, elapsed, elapsed / 60,
    )

    # Diagnostic: per-qubit Bloch-sphere magnitudes.
    # A fully mixed state has |b| = 0; a pure state has |b| = 1.
    mags = np.zeros(n_qubits)
    for q in range(n_qubits):
        mags[q] = np.sqrt(
            bloch[:, 3 * q] ** 2
            + bloch[:, 3 * q + 1] ** 2
            + bloch[:, 3 * q + 2] ** 2
        ).mean()
    logger.info(
        "  Bloch magnitudes per qubit: %s (mean=%.3f)",
        np.round(mags, 3).tolist(), float(mags.mean()),
    )

    if cache_path is not None:
        os.makedirs(os.path.dirname(cache_path), exist_ok=True)
        np.save(cache_path, bloch)
        logger.info("  Saved Bloch vectors to %s", cache_path)

    return bloch


def compute_bscm_pqk_gram(
    bloch: np.ndarray,
    n_qubits: int = config.N_QUBITS,
    gamma: float = config.PQK_GAMMA,
) -> np.ndarray:
    """Build the Projected Quantum Kernel gram matrix from Bloch vectors.

    K(x, x') = exp( -γ · ½ · Σ_q ||b_q(x) − b_q(x')||² )

    where b_q = (⟨X_q⟩, ⟨Y_q⟩, ⟨Z_q⟩) is the 3-component Bloch vector
    of qubit q after the feature-map circuit.

    The kernel is equivalent to an RBF kernel on the concatenated Bloch
    vectors, with the per-qubit L2 distances summed before exponentiation.

    Args:
        bloch:    (N, 3 * n_qubits) Bloch-vector array from
                  extract_bscm_bloch_vectors().
        n_qubits: Number of qubits.
        gamma:    RBF bandwidth parameter.

    Returns:
        (N, N) symmetric positive-definite gram matrix with unit diagonal.
    """
    N = len(bloch)
    b = bloch.reshape(N, n_qubits, 3)  # (N, n_q, 3)

    K = np.zeros((N, N), dtype=np.float64)
    for i in range(N):
        diff = b[i] - b                    # (N, n_q, 3)
        sq_dist = (diff * diff).sum(axis=2)  # (N, n_q)
        total_dist = 0.5 * sq_dist.sum(axis=1)  # (N,)
        K[i] = np.exp(-gamma * total_dist)

    np.fill_diagonal(K, 1.0)
    K = (K + K.T) / 2.0  # Enforce numerical symmetry.
    return K


