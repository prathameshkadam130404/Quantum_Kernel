# Self-test
# ============================================================================

def _self_test() -> None:
    """Numerical validation of BSCM kernel structural properties.

    Tests:
        1. Coupling coefficient bounds:  |alpha|, |beta| <= 1/2.
        2. Boundary case x_i = x_j -> Hamiltonian is (1/2)I + (1/2) XX.
        3. Kernel symmetry:  K = K.T  (within numerical noise).
        4. Kernel diagonal:  K[i, i] = 1.
        5. Kernel PSD: smallest eigenvalue >= -tol.
        6. Numerical P2 on the circuit:  the fully-applied gate has zero
           ZZ Pauli component when measured as a 2-qubit unitary on a
           random pair.  (Sanity check that the implementation matches
           the derivation.)
    """
    import pennylane as qml

    print("=" * 60)
    print("  BSCM Kernel Self-Test")
    print("=" * 60)

    np.random.seed(config.RANDOM_SEED)
    n_q = 4
    N = 16
    X = np.random.rand(N, n_q) * np.pi

    # 1. Coefficient bounds.
    print("\n[1] Coupling coefficient bounds...")
    rng = np.random.default_rng(0)
    worst_a, worst_b = 0.0, 0.0
    for _ in range(10000):
        x_i, x_j = rng.uniform(-2 * np.pi, 2 * np.pi, size=2)
        a, b = bscm_xy_coefficients(x_i, x_j)
        worst_a = max(worst_a, abs(a))
        worst_b = max(worst_b, abs(b))
    assert worst_a <= 0.5 + 1e-12 and worst_b <= 0.5 + 1e-12
    print(f"  max |alpha| = {worst_a:.4f}    max |beta| = {worst_b:.4f}    OK.")

    # 2. Boundary x_i = x_j.
    print("\n[2] Boundary x_i = x_j ...")
    a, b = bscm_xy_coefficients(0.7, 0.7)
    assert abs(a - 0.5 * np.cos(0.7) ** 2) < 1e-12
    assert abs(b - 0.5 * np.sin(0.7) ** 2) < 1e-12
    assert abs((a + b) - 0.5) < 1e-12  # cos^2 + sin^2 = 1
    print(f"  alpha + beta = 1/2  for redundant features.  OK.")

    # 3. Kernel symmetry, diagonal, PSD.
    print(f"\n[3-5] Building BSCM kernel ({n_q} qubits, N={N})...")
    K = compute_bscm_fidelity_kernel(
        X, n_qubits=n_q, reps=2, tau=1.0,
        coupling_threshold=1e-4, connectivity="all",
    )
    asym = float(np.max(np.abs(K - K.T)))
    diag_err = float(np.max(np.abs(K.diagonal() - 1.0)))
    eig = np.linalg.eigvalsh((K + K.T) / 2)
    print(f"  asymmetry              = {asym:.2e}")
    print(f"  diagonal error         = {diag_err:.2e}")
    print(f"  min eigenvalue         = {eig.min():.6e}")
    assert asym < 1e-10
    assert diag_err < 1e-10
    assert eig.min() > -1e-8

    # 6. Numerical P2 on the circuit, single pair, single rep.
    print("\n[6] Numerical P2 on the circuit (single pair, single rep)...")
    dev = qml.device("default.qubit", wires=2)

    @qml.qnode(dev, diff_method=None)
    def pair_unitary_zz():
        # Apply one BSCM rep on a 2-qubit register, measure ZZ.
        x = np.array([0.7, 1.3])  # arbitrary
        apply_bscm_feature_map(
            x, n_qubits=2, reps=1, tau=1.0,
            coupling_threshold=1e-4, connectivity="all",
        )
        return qml.expval(qml.PauliZ(0) @ qml.PauliZ(1))

    # The Hadamard layer + RZ layer alone produces <ZZ> = 0 on |00>:
    # H|0> = |+>; RZ doesn't change <Z> on |+>; so <Z_0> = <Z_1> = 0
    # and <Z_0 Z_1> = 0 (independent of tau and the IsingXX/IsingYY).
    val = float(pair_unitary_zz())
    print(f"  <ZZ> after BSCM layer = {val:.2e}   (expected ~0 by construction)")
    assert abs(val) < 1e-10

    print("\n" + "=" * 60)
    print("  ALL BSCM SELF-TESTS PASSED")
    print("=" * 60)


if __name__ == "__main__":
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s [%(name)s] %(levelname)s: %(message)s",
    )
    _self_test()
