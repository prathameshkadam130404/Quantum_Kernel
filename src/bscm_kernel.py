def _build_fidelity_circuit(
    n_qubits: int,
    reps: int,
    tau: float,
    coupling_threshold: float,
    connectivity: str,
    bell_weights: Tuple[float, float, float, float] = BELL_WEIGHT_PRESETS["uniform"],
    singlet_gated: bool = False,
):
    """Construct the QNode that computes |<0...0| U^dagger(x2) U(x1) |0...0>|^2."""
    import pennylane as qml

    dev = config.get_device(n_qubits)

    @qml.qnode(dev, diff_method=None)
    def circuit(x1, x2):
        apply_bscm_feature_map(
            x1, n_qubits, reps, tau, coupling_threshold, connectivity,
            bell_weights, singlet_gated,
        )
        apply_bscm_feature_map_adjoint(
            x2, n_qubits, reps, tau, coupling_threshold, connectivity,
            bell_weights, singlet_gated,
        )
        return qml.probs(wires=range(n_qubits))

    return circuit


def compute_bscm_fidelity_kernel(
    X: np.ndarray,
    X2: Optional[np.ndarray] = None,
    n_qubits: int = config.N_QUBITS,
    reps: int = config.ZZ_REPS,
    tau: float = 1.0,
    coupling_threshold: float = 1e-4,
    connectivity: str = "all",
    bell_weights: Tuple[float, float, float, float]
        = BELL_WEIGHT_PRESETS["uniform"],
    kernel_save_path: Optional[str] = None,
    desc: str = "BSCM",
    singlet_gated: bool = False,
) -> np.ndarray:
    """Compute the BSCM fidelity kernel matrix.

    For X2 is None this returns the symmetric N x N Gram matrix using
    upper-triangle symmetry (only N (N+1)/2 circuit evaluations).  For
    X2 not None it returns an M x N rectangular matrix.

    Caching: if `kernel_save_path` exists on disk it is loaded and
    returned; otherwise the computed matrix is saved at that path.

    If singlet_gated=True, the singlet-fraction modulation
    sin^2((x_i - x_j)/2) is applied to every pair's Pauli coupling
    coefficients before emitting Ising gates.  See
    apply_bscm_feature_map() for details.
    """
    if kernel_save_path is not None and os.path.exists(kernel_save_path):
        logger.info(f"[CACHE] Loading BSCM kernel from {kernel_save_path}")
        return np.load(kernel_save_path)

    circuit = _build_fidelity_circuit(
        n_qubits, reps, tau, coupling_threshold, connectivity,
        bell_weights, singlet_gated,
    )

    if kernel_save_path is not None:
        os.makedirs(os.path.dirname(kernel_save_path), exist_ok=True)

    n = len(X)
    if X2 is None:
        # Row-level checkpointing for crash recovery on multi-hour runs.
        # We save the partially-filled K and a `next_i` marker after each row.
        ckpt_path = (kernel_save_path + ".ckpt.npz") if kernel_save_path else None
        start_i = 0
        if ckpt_path is not None and os.path.exists(ckpt_path):
            ck = np.load(ckpt_path)
            if ck["n"].item() == n:
                K = ck["K"].copy()
                start_i = int(ck["next_i"].item())
                logger.info("[CKPT] Resuming %s from row %d/%d", desc, start_i, n)
            else:
                K = np.ones((n, n), dtype=np.float64)
        else:
            K = np.ones((n, n), dtype=np.float64)

        n_evals_total = n * (n - 1) // 2
        n_evals_done = start_i * n - start_i * (start_i + 1) // 2
        pbar = tqdm(total=n_evals_total, desc=f"{desc} K({n}x{n})", unit="eval",
                    initial=n_evals_done)
        for i in range(start_i, n):
            for j in range(i + 1, n):
                p0 = float(circuit(X[i], X[j])[0])
                K[i, j] = p0
                K[j, i] = p0
                pbar.update(1)
            if ckpt_path is not None and ((i + 1) % 25 == 0 or i == n - 1):
                np.savez(ckpt_path, K=K, next_i=np.array(i + 1), n=np.array(n))
        pbar.close()
    else:
        m = len(X2)
        K = np.zeros((m, n), dtype=np.float64)
        pbar = tqdm(total=m * n, desc=f"{desc} K({m}x{n})", unit="eval")
        for i in range(m):
            for j in range(n):
                K[i, j] = float(circuit(X[j], X2[i])[0])
                pbar.update(1)
        pbar.close()

    if kernel_save_path is not None:
        os.makedirs(os.path.dirname(kernel_save_path), exist_ok=True)
        np.save(kernel_save_path, K)
        logger.info(f"Saved BSCM kernel to {kernel_save_path}")
        ckpt_path = kernel_save_path + ".ckpt.npz"
        try:
            if os.path.exists(ckpt_path):
                os.remove(ckpt_path)
        except OSError:
            pass  # Windows occasionally holds the file briefly; non-critical.

    return K


