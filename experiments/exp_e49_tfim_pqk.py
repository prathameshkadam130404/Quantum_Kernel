"""
E49: TFIM phase classification with BSCM-uniform-PQK vs Standard-ZZ-PQK.

Tests the BSCM-vs-Standard-ZZ architectural gap on intrinsically-quantum
features: the ground-state expectation values of a transverse-field Ising
model (TFIM).  Complements E43 (UCI tabular non-quantum domains) by
covering the quantum-physics domain that some QML theory predicts is most
favourable to quantum kernels.

Dataset
-------
600 samples from a 16-site open-boundary TFIM chain, half in the
ferromagnetic range (h/J in (0.05, 0.9)) and half in the paramagnetic
range (h/J in (1.1, 2.5)); the QCP slab (0.9, 1.1) is excluded so the
binary labels are sharp.  16 features per sample:
    15 nearest-neighbour <Z_i Z_{i+1}> correlators
     1 average transverse magnetisation <X>
Generated by scripts/generate_tfim_dataset.py -> data/processed/tfim_phase_L16.npz.

Protocol
--------
* StandardScaler -> PCA(16) -> MinMaxScaler[0, pi].
* BSCM-uniform-PQK and Standard-ZZ-PQK at n=16, depth=6, tau=0.25.
* Joint (C, gamma) inner-CV search where gamma ranges over
  GAMMA_MULTIPLIERS * dyn_gamma (the multiplier grid imported from
  exp_e43_generalization_pqk).  Identical search for both kernels.
  E49 does NOT additionally use the absolute-gamma grid that E43 sweeps;
  the TFIM features are bounded by physical observables in [-1, 1] so
  multiplier-only tuning suffices.  Both kernels use the same search;
  the symmetry property that the architectural claim depends on is
  preserved.
* Classical baselines: tuned RBF-SVM, Random Forest.
* 5 stratified shuffle splits, master seed 42.

Output
------
results/e49_tfim/tfim_phase_results.json
results/e49_tfim/exp_e49.log

Usage
-----
    python scripts/generate_tfim_dataset.py    # build the .npz if absent
    python experiments/exp_e49_tfim_pqk.py
"""
from __future__ import annotations

import json
import logging
import os
import sys
import time
from typing import Dict

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import config

# Reuse the E43 (C, gamma) search machinery so both experiments evaluate
# both quantum kernels on the identical hyperparameter grid.
from experiments.exp_e43_generalization_pqk import (
    N_QUBITS, DEPTH, CV_FOLDS, C_GRID, GAMMA_GRID,
    GAMMA_MULTIPLIERS, INNER_CV_FOLDS,
    extract_bloch_vectors,
)
from sklearn.decomposition import PCA
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, f1_score
from sklearn.model_selection import GridSearchCV, StratifiedShuffleSplit
from sklearn.preprocessing import MinMaxScaler, StandardScaler
from sklearn.svm import SVC

OUT_DIR = os.path.join(config.RESULTS_DIR, "e49_tfim")
os.makedirs(OUT_DIR, exist_ok=True)
LOG_PATH = os.path.join(OUT_DIR, "exp_e49.log")
SUMMARY_PATH = os.path.join(OUT_DIR, "tfim_phase_results.json")

TFIM_NPZ = os.path.join(config.PROCESSED_DIR, "tfim_phase_L16.npz")
N_SPLITS = 5

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(name)s] %(levelname)s: %(message)s",
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler(LOG_PATH, mode="w"),
    ],
)
log = logging.getLogger("exp_e49")


def _load_dataset() -> Dict[str, np.ndarray]:
    if not os.path.exists(TFIM_NPZ):
        log.error(
            "Missing %s.  Run `python scripts/generate_tfim_dataset.py` "
            "first to build the dataset.", TFIM_NPZ,
        )
        sys.exit(1)
    d = np.load(TFIM_NPZ)
    X_raw, y = d["X_raw"], d["y"]
    log.info("  TFIM dataset: N=%d, L=%d sites, feature_dim=%d, "
             "class counts=%s",
             len(y), int(d["L"]), X_raw.shape[1],
             dict(zip(*np.unique(y, return_counts=True))))
    return {"X_raw": X_raw, "y": y, "h_over_J": d["h_over_J"]}


def _quantum_pipeline_fold(X_raw: np.ndarray, y: np.ndarray, tr, te) -> dict:
    """Run BSCM-uniform-PQK and Standard-ZZ-PQK on one fold."""
    sc = StandardScaler().fit(X_raw[tr])
    X_tr_std = sc.transform(X_raw[tr])
    X_te_std = sc.transform(X_raw[te])

    pca = PCA(n_components=N_QUBITS, random_state=42).fit(X_tr_std)
    X_tr_pca = pca.transform(X_tr_std)
    X_te_pca = pca.transform(X_te_std)

    mm = MinMaxScaler(feature_range=(0, np.pi)).fit(X_tr_pca)
    X_tr_enc = mm.transform(X_tr_pca).clip(0, np.pi).astype(np.float32)
    X_te_enc = mm.transform(X_te_pca).clip(0, np.pi).astype(np.float32)

    fold_out = {}
    for q_name, is_std in [("Standard-ZZ", True), ("BSCM-uniform", False)]:
        bloch_tr = extract_bloch_vectors(X_tr_enc, q_name, is_standard=is_std)
        bloch_te = extract_bloch_vectors(X_te_enc, q_name, is_standard=is_std)
        b_tr = bloch_tr.reshape(len(bloch_tr), -1).astype(np.float64)
        b_te = bloch_te.reshape(len(bloch_te), -1).astype(np.float64)
        var = float(np.var(b_tr))
        d = b_tr.shape[1]
        dyn_gamma = 1.0 / (d * var) if var > 0 else 1.0

        sq_norms_tr = np.sum(b_tr ** 2, axis=1)
        sq_norms_te = np.sum(b_te ** 2, axis=1)
        sq_dists_tr = np.clip(
            sq_norms_tr[:, None] + sq_norms_tr[None, :] - 2.0 * (b_tr @ b_tr.T),
            0, None,
        )
        sq_dists_te = np.clip(
            sq_norms_te[:, None] + sq_norms_tr[None, :] - 2.0 * (b_te @ b_tr.T),
            0, None,
        )

        best_score = -np.inf
        best_gm = 1.0
        best_C = 1.0
        for gm in GAMMA_MULTIPLIERS:
            gamma = dyn_gamma * gm
            K_tr_g = np.exp(-gamma * 0.5 * sq_dists_tr)
            np.fill_diagonal(K_tr_g, 1.0)
            K_tr_g = (K_tr_g + K_tr_g.T) / 2.0
            inner = GridSearchCV(
                SVC(kernel="precomputed", class_weight="balanced"),
                {"C": C_GRID}, cv=INNER_CV_FOLDS,
                scoring="f1_macro", n_jobs=-1,
            )
            inner.fit(K_tr_g, y[tr])
            cv_score = float(inner.best_score_)
            if cv_score > best_score:
                best_score = cv_score
                best_gm = float(gm)
                best_C = float(inner.best_params_["C"])

        final_gamma = dyn_gamma * best_gm
        K_tr = np.exp(-final_gamma * 0.5 * sq_dists_tr)
        np.fill_diagonal(K_tr, 1.0)
        K_tr = (K_tr + K_tr.T) / 2.0
        K_te = np.exp(-final_gamma * 0.5 * sq_dists_te)
        final = SVC(kernel="precomputed", class_weight="balanced", C=best_C)
        final.fit(K_tr, y[tr])
        yp = final.predict(K_te)
        fold_out[q_name] = {
            "f1": float(f1_score(y[te], yp, average="macro")),
            "acc": float(accuracy_score(y[te], yp)),
            "best_C": best_C,
            "best_gamma_multiplier": best_gm,
            "dyn_gamma_train": float(dyn_gamma),
        }
        log.info("    %s: f1=%.4f acc=%.4f  best_C=%g  gm=%g",
                 q_name, fold_out[q_name]["f1"], fold_out[q_name]["acc"],
                 best_C, best_gm)
    return fold_out


def _classical_pipeline_fold(X_raw: np.ndarray, y: np.ndarray, tr, te) -> dict:
    sc = StandardScaler().fit(X_raw[tr])
    X_tr_std = sc.transform(X_raw[tr])
    X_te_std = sc.transform(X_raw[te])

    rbf = GridSearchCV(
        SVC(kernel="rbf", class_weight="balanced"),
        {"C": C_GRID, "gamma": GAMMA_GRID}, cv=CV_FOLDS, n_jobs=-1,
    )
    rbf.fit(X_tr_std, y[tr])
    yp_rbf = rbf.predict(X_te_std)

    rf = RandomForestClassifier(
        n_estimators=500, class_weight="balanced",
        random_state=42, n_jobs=-1,
    )
    rf.fit(X_tr_std, y[tr])
    yp_rf = rf.predict(X_te_std)
    return {
        "RBF-SVM": {
            "f1": float(f1_score(y[te], yp_rbf, average="macro")),
            "acc": float(accuracy_score(y[te], yp_rbf)),
        },
        "RandomForest": {
            "f1": float(f1_score(y[te], yp_rf, average="macro")),
            "acc": float(accuracy_score(y[te], yp_rf)),
        },
    }


def main() -> None:
    log.info("=" * 72)
    log.info("  E49 TFIM phase classification "
             "(BSCM-uniform vs Standard-ZZ PQK + classical baselines)")
    log.info("=" * 72)

    data = _load_dataset()
    X_raw, y = data["X_raw"], data["y"]

    sss = StratifiedShuffleSplit(
        n_splits=N_SPLITS, test_size=0.3, random_state=42,
    )

    per_fold = []
    fold = 0
    for tr, te in sss.split(X_raw, y):
        fold += 1
        log.info("Fold %d/%d -- |tr|=%d, |te|=%d",
                 fold, N_SPLITS, len(tr), len(te))
        t0 = time.time()
        rec = _quantum_pipeline_fold(X_raw, y, tr, te)
        rec.update(_classical_pipeline_fold(X_raw, y, tr, te))
        log.info("  fold done in %.1fs", time.time() - t0)
        per_fold.append(rec)

    methods = ["BSCM-uniform", "Standard-ZZ", "RBF-SVM", "RandomForest"]
    summary: Dict[str, dict] = {}
    for m in methods:
        f1s = [r[m]["f1"] for r in per_fold]
        accs = [r[m]["acc"] for r in per_fold]
        s = {
            "f1_mean": float(np.mean(f1s)),
            "f1_std": float(np.std(f1s)),
            "acc_mean": float(np.mean(accs)),
            "acc_std": float(np.std(accs)),
            "f1_per_split": [float(x) for x in f1s],
            "acc_per_split": [float(x) for x in accs],
        }
        if m in ("BSCM-uniform", "Standard-ZZ"):
            s["best_C_per_split"] = [
                float(r[m]["best_C"]) for r in per_fold
            ]
            s["best_gamma_multiplier_per_split"] = [
                float(r[m]["best_gamma_multiplier"]) for r in per_fold
            ]
            s["dyn_gamma_train_per_split"] = [
                float(r[m]["dyn_gamma_train"]) for r in per_fold
            ]
        summary[m] = s

    # Architectural gap.
    bscm_f1 = np.asarray(summary["BSCM-uniform"]["f1_per_split"])
    zz_f1 = np.asarray(summary["Standard-ZZ"]["f1_per_split"])
    gap_summary = {
        "bscm_minus_zz_f1": float((bscm_f1 - zz_f1).mean()),
        "bscm_minus_zz_f1_per_split": [float(x) for x in (bscm_f1 - zz_f1)],
        "bscm_minus_zz_acc": float(
            np.mean(np.asarray(summary["BSCM-uniform"]["acc_per_split"]) -
                    np.asarray(summary["Standard-ZZ"]["acc_per_split"]))
        ),
    }

    out = {
        "protocol": {
            "n_qubits": N_QUBITS,
            "depth": DEPTH,
            "tau": 0.25,
            "n_splits": N_SPLITS,
            "test_fraction": 0.3,
            "split_seed": 42,
            "C_grid": C_GRID,
            "gamma_multipliers": GAMMA_MULTIPLIERS,
            "rbf_gamma_grid": GAMMA_GRID,
            "inner_cv_folds": INNER_CV_FOLDS,
        },
        "dataset": {
            "name": "TFIM phase classification",
            "L_sites": 16,
            "h_over_J_ferro_range": [0.05, 0.9],
            "h_over_J_para_range": [1.1, 2.5],
            "n_samples": int(len(y)),
            "feature_description": (
                "15 nearest-neighbour <Z_i Z_{i+1}> correlators + 1 average "
                "<X> on the ground state of -J sum ZZ - h sum X (open BC)"
            ),
        },
        "summary": summary,
        "architectural_gap": gap_summary,
    }
    with open(SUMMARY_PATH, "w") as f:
        json.dump(out, f, indent=2)
    log.info("Wrote %s", SUMMARY_PATH)

    log.info("")
    log.info("=" * 72)
    log.info("  TFIM phase classification SUMMARY")
    log.info("=" * 72)
    log.info("%-15s %12s %12s", "method", "f1", "acc")
    for m in methods:
        s = summary[m]
        log.info("%-15s %.4f+/-%.4f %.4f+/-%.4f",
                 m, s["f1_mean"], s["f1_std"], s["acc_mean"], s["acc_std"])
    log.info("BSCM - ZZ gap: f1=%+.4f, acc=%+.4f",
             gap_summary["bscm_minus_zz_f1"],
             gap_summary["bscm_minus_zz_acc"])


if __name__ == "__main__":
    main()
