"""
E44: Synthetic-data positive control for the FQK evaluation pipeline.

Constructs a small (N=200, n=8) binary classification task whose data
distribution is generated by a non-commuting Hamiltonian (designed to
favour FQK over RBF), then evaluates Standard-ZZ-FQK, BSCM-uniform-FQK,
and tuned RBF-SVM on the resulting task.

Purpose: this is a sanity check, not a quantum-advantage claim.  The
paper reports E44 as a positive control that verifies the FQK pipeline
is capable of revealing an advantage when the data distribution is
matched to the circuit geometry; on real data (E26/E32/E38) no
advantage appears, which is the expected regime under bandwidth-tuning
convergence theory (Canatar et al., TMLR 2023; Florez-Ablan, Roth and
Schnabel, Quantum Sci. Tech. 10, 035051 (2025)).

The fidelity kernel rather than PQK is used here because the question
is about pure two-qubit representational geometry; FQK scales O(N^2)
in circuit calls so N=200 is the practical scale.
"""
import os
import sys
import json
import time
import logging
import numpy as np
from typing import Tuple
from tqdm import tqdm

import pennylane as qml
from sklearn.svm import SVC
from sklearn.model_selection import StratifiedShuffleSplit, GridSearchCV
from sklearn.metrics import f1_score, accuracy_score
from sklearn.preprocessing import StandardScaler, MinMaxScaler

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import config
from src.bscm_kernel import bscm_pauli_coefficients

# ============================================================================
# CONFIGURATION
# ============================================================================
N_QUBITS = 8
N_SAMPLES = 200
DEPTH = 2
C_GRID = [0.1, 1.0, 10.0, 100.0, 1000.0]
GAMMA_GRID = ["scale", "auto", 0.001, 0.01, 0.1, 1.0, 10.0]

OUT_DIR = os.path.join(config.RESULTS_DIR, "e44_quantum_advantage")
os.makedirs(OUT_DIR, exist_ok=True)

logging.basicConfig(
    level=logging.INFO, 
    format="%(asctime)s [%(name)s] %(levelname)s:   %(message)s",
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler(os.path.join(OUT_DIR, "exp_e44.log"), mode="w"),
    ]
)
log = logging.getLogger("exp_e44")

# ============================================================================
# QUANTUM NATIVE DATASET GENERATION
# ============================================================================

def generate_quantum_native_dataset(n_samples: int, n_qubits: int) -> Tuple[np.ndarray, np.ndarray]:
    """
    Generates a dataset where the decision boundary is determined by a highly
    oscillatory, non-commuting quantum process, making it classically hard.
    """
    np.random.seed(42)
    X = np.random.uniform(0, np.pi, size=(n_samples, n_qubits)).astype(np.float32)
    y = np.zeros(n_samples, dtype=int)
    
    dev = qml.device("default.qubit", wires=n_qubits)
    
    @qml.qnode(dev, diff_method=None)
    def label_circuit(x):
        # 1. Non-linear entanglement
        for i in range(n_qubits):
            qml.Hadamard(wires=i)
            qml.RZ(x[i], wires=i)
        
        # 2. Highly non-commuting operations
        for i in range(n_qubits - 1):
            qml.IsingXX(x[i] * x[i+1], wires=[i, i+1])
            qml.IsingYY(x[i] * x[i+1], wires=[i, i+1])
            
        for i in range(n_qubits):
            qml.RX(x[i], wires=i)
            
        # Global parity observable
        obs = qml.PauliZ(0)
        for i in range(1, n_qubits):
            obs = obs @ qml.PauliZ(i)
        return qml.expval(obs)
        
    log.info(f"Generating Classically Hard Dataset (N={n_samples})...")
    for i in range(n_samples):
        exp_val = label_circuit(X[i])
        y[i] = 1 if exp_val > 0 else 0
        
    return X, y

# ============================================================================
# FIDELITY QUANTUM KERNELS (FQK)
# ============================================================================

def standard_zz_ansatz(x):
    for r in range(DEPTH):
        for i in range(N_QUBITS):
            qml.Hadamard(wires=i)
            qml.RZ(x[i], wires=i)
        for i in range(N_QUBITS - 1):
            theta = 2.0 * (np.pi - x[i]) * (np.pi - x[i+1])
            qml.IsingZZ(theta, wires=[i, i+1])

def bscm_ansatz(x):
    TAU = 0.25
    for r in range(DEPTH):
        for i in range(N_QUBITS):
            qml.Hadamard(wires=i)
            qml.RZ(x[i], wires=i)
        for i in range(N_QUBITS - 1):
            a_xx, a_yy, a_zz = bscm_pauli_coefficients(x[i], x[i+1], (1.0, 1.0, 1.0, 1.0))
            if abs(a_xx) > 1e-5: qml.IsingXX(2.0 * TAU * a_xx, wires=[i, i+1])
            if abs(a_yy) > 1e-5: qml.IsingYY(2.0 * TAU * a_yy, wires=[i, i+1])


dev_fqk = qml.device("default.qubit", wires=N_QUBITS)

@qml.qnode(dev_fqk, diff_method=None)
def kernel_circuit_zz(x1, x2):
    standard_zz_ansatz(x1)
    qml.adjoint(standard_zz_ansatz)(x2)
    return qml.probs(wires=range(N_QUBITS))

@qml.qnode(dev_fqk, diff_method=None)
def kernel_circuit_bscm(x1, x2):
    bscm_ansatz(x1)
    qml.adjoint(bscm_ansatz)(x2)
    return qml.probs(wires=range(N_QUBITS))

def compute_fqk_gram_matrix(X: np.ndarray, name: str) -> np.ndarray:
    N = len(X)
    K = np.eye(N)
    
    kernel_func = kernel_circuit_bscm if name == "BSCM-uniform" else kernel_circuit_zz
    
    t0 = time.time()
    total_pairs = (N * (N - 1)) // 2
    
    log.info(f"  Computing {name} FQK Matrix ({total_pairs} pairs)...")
    
    with tqdm(total=total_pairs, desc=f"{name} FQK", bar_format="{l_bar}{bar} | {n_fmt}/{total_fmt} [{elapsed}<{remaining}, {rate_fmt}]") as pbar:
        for i in range(N):
            for j in range(i+1, N):
                fidelity = kernel_func(X[i], X[j])[0] # Prob of all-zero state
                K[i, j] = fidelity
                K[j, i] = fidelity
                pbar.update(1)
                
    # Secure numeric stability
    K = (K + K.T) / 2.0
    np.fill_diagonal(K, 1.0)
    
    log.info(f"  {name} Matrix completed in {time.time()-t0:.1f}s")
    return K


# ============================================================================
# EVALUATION
# ============================================================================

def run_experiment():
    X, y = generate_quantum_native_dataset(N_SAMPLES, N_QUBITS)
    
    log.info(f"Class distribution: {np.bincount(y)}")
    
    # 5-Fold Stratified CV
    sss = StratifiedShuffleSplit(n_splits=5, test_size=0.3, random_state=42)
    
    results = {
        "RBF-SVM": {"acc": []},
        "Standard-ZZ (FQK)": {"acc": []},
        "BSCM-uniform (FQK)": {"acc": []}
    }
    
    log.info("\nEvaluating Classical RBF-SVM...")
    for tr, te in sss.split(X, y):
        scaler = StandardScaler()
        X_tr = scaler.fit_transform(X[tr])
        X_te = scaler.transform(X[te])
        
        clf = GridSearchCV(SVC(kernel="rbf", class_weight="balanced"), {"C": C_GRID, "gamma": GAMMA_GRID}, cv=3, n_jobs=-1)
        clf.fit(X_tr, y[tr])
        yp = clf.predict(X_te)
        results["RBF-SVM"]["acc"].append(accuracy_score(y[te], yp))
        
    
    log.info("\nEvaluating Quantum Kernels (FQK)...")
    
    for q_name in ["Standard-ZZ", "BSCM-uniform"]:
        # Precompute the entire FQK Matrix
        # Because FQK is shift-invariant and exact, we compute it once globally.
        cache_file = os.path.join(OUT_DIR, f"cache_{q_name}.npz")
        if os.path.exists(cache_file):
            K_full = np.load(cache_file)["K"]
            log.info(f"  Loaded {q_name} from cache.")
        else:
            K_full = compute_fqk_gram_matrix(X, q_name)
            np.savez_compressed(cache_file, K=K_full)
            
        full_name = f"{q_name} (FQK)"
        for tr, te in sss.split(X, y):
            K_tr = K_full[np.ix_(tr, tr)]
            K_te = K_full[np.ix_(te, tr)]
            
            clf = GridSearchCV(SVC(kernel="precomputed", class_weight="balanced"), {"C": C_GRID}, cv=3, n_jobs=-1)
            clf.fit(K_tr, y[tr])
            yp = clf.predict(K_te)
            results[full_name]["acc"].append(accuracy_score(y[te], yp))


    # Aggregate and Print
    log.info("\n\n" + "="*60)
    log.info("QUANTUM SUPREMACY BENCHMARK SUMMARY (N=200, n=8)")
    log.info("="*60)
    log.info(f"{'Kernel Type':<25s} | {'Mean Accuracy':<15s}")
    log.info("-" * 60)
    for k, v in results.items():
        acc = np.mean(v["acc"])
        std = np.std(v["acc"])
        log.info(f"{k:<25s} | {acc:.4f} +/- {std:.4f}")
    
    with open(os.path.join(OUT_DIR, "supremacy_results.json"), "w") as f:
        json.dump({k: {"acc_mean": float(np.mean(v["acc"])), "acc_std": float(np.std(v["acc"]))}
                   for k, v in results.items()}, f, indent=2)

if __name__ == "__main__":
    run_experiment()
